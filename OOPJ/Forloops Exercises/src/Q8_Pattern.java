
public class Q8_Pattern {
	public static void main(String args[]) {
		
		for (int iTemp = 0 ; iTemp <= 5; iTemp++) {
			
			for (int jTemp = 1; jTemp <= 6 - iTemp; jTemp++) {
				
				System.out.print(jTemp + " ");
				
			}
			
			System.out.println();
			
			
			
		}
		
		
		
	}
}
